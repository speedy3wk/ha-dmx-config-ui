const TEXT = { en, de };
export type Lang = keyof typeof TEXT;

export const languageOf = (hass?: HomeAssistant): Lang => {
  const lang = hass?.locale?.language ?? hass?.language ?? navigator.language ?? "en";
  return lang.toLowerCase().startsWith("de") ? "de" : "en";
};

export type Translate = (key: TextKey, params?: Record<string, string | number>) => string;

export const translator =
  (lang: Lang): Translate =>
  (key, params) => {
    const template = TEXT[lang][key] ?? en[key] ?? key;
    if (!params) return template;
    return template.replace(/\{(\w+)\}/g, (match, name: string) =>
      name in params ? String(params[name]) : match
    );
  };

const PARAM_CODES = new Set(["range", "choice", "setup_char", "overflow", "overlap"]);

export const issueText = (t: Translate, issue: ValidationIssue): string => {
  const key = `err_${issue.code}` as TextKey;
  if (!(key in en)) return issue.message;
  // Backend issues carry no params: fall back to their (English) message.
  if (PARAM_CODES.has(issue.code) && !issue.params) return issue.message;
  return t(key, issue.params);
};
