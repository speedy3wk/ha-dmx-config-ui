"""Tests for YAML rendering and include handling."""

from __future__ import annotations

import pytest
import yaml

from custom_components.dmx_config_ui.files import (
    add_dmx_include,
    find_top_level_block,
    render_dmx_yaml,
)


def test_render_dmx() -> None:
    content = render_dmx_yaml({"fixtures_folder": "fixtures"})
    assert content.startswith("# Generated by DMX Config UI")
    assert yaml.safe_load(content) == {"fixtures": {"folder": "fixtures"}}


CONFIGURATION = (
    "default_config:\n"
    "dmx:\n"
    "  artnet:\n"
    "    universes:\n"
    "      - 1:\n"
    "\n"
    "          devices: []\n"
    "  # trailing comment of the block\n"
    "# comment before light\n"
    "light:\n"
    "  - platform: template\n"
)


@pytest.mark.parametrize(
    ("configuration", "key", "expected"),
    [
        (None, "dmx", None),
        ("", "dmx", None),
        (CONFIGURATION, "dmx", (1, 7)),
        (CONFIGURATION, "light", (9, 11)),
        (CONFIGURATION, "default_config", (0, 1)),
        ("dmxfoo:\n  a: 1\n", "dmx", None),
        ("dmx: !include x.yaml\n", "dmx", (0, 1)),
        ("  dmx:\n", "dmx", None),
    ],
)
def test_find_top_level_block(configuration, key: str, expected) -> None:
    assert find_top_level_block(configuration, key) == expected


def test_add_dmx_include_replaces_block() -> None:
    updated, replaced = add_dmx_include(CONFIGURATION, "gen.yaml")
    assert replaced is True
    assert updated == (
        "default_config:\n"
        "dmx: !include gen.yaml\n"
        "  # trailing comment of the block\n"
        "# comment before light\n"
        "light:\n"
        "  - platform: template\n"
    )
    assert yaml.safe_load(updated.replace("!include gen.yaml", "x"))["light"]
    assert add_dmx_include(updated, "gen.yaml") == (updated, False)


def test_add_dmx_include_appends() -> None:
    assert add_dmx_include(None, "gen.yaml") == ("dmx: !include gen.yaml\n", False)
    assert add_dmx_include("a: 1\n", "gen.yaml") == ("a: 1\n\ndmx: !include gen.yaml\n", False)
