"""Tests for YAML rendering and include handling."""

from __future__ import annotations

import pytest
import yaml

from custom_components.dmx_config_ui.files import (
    add_dmx_include,
    add_include,
    find_top_level_block,
    is_included,
    is_valid_include_file,
    render_dmx_yaml,
    render_yaml,
)
from custom_components.dmx_config_ui.model import normalize_config, to_platform_entries


def test_render_is_valid_yaml_with_special_characters(sample_config: dict) -> None:
    sample_config["nodes"][0]["universes"][0]["devices"][0]["name"] = "a: b # c 'd' \"e\""
    config = normalize_config(sample_config)
    content = render_yaml(config)
    assert content.startswith("# Generated by DMX Config UI")
    assert yaml.safe_load(content) == to_platform_entries(config)


def test_render_empty() -> None:
    assert yaml.safe_load(render_yaml({"nodes": []})) == []


def test_render_layout(sample_config: dict) -> None:
    content = render_yaml(normalize_config(sample_config))
    assert "- platform: artnet_led\n  host: 192.168.0.10\n" in content
    assert (
        "  universes:\n    0:\n      send_partial_universe: true\n"
        "      devices:\n        - channel: 1\n" in content
    )


@pytest.mark.parametrize(
    ("configuration", "expected"),
    [
        (None, False),
        ("light: !include dmx_config_ui.yaml\n", True),
        ("light dmx_config_ui: !include 'dmx_config_ui.yaml'  # x\n", True),
        ("# light: !include dmx_config_ui.yaml\n", False),
        ("light: !include other.yaml\n", False),
        ("light: !include dmx_config_ui.yaml.bak\n", False),
    ],
)
def test_is_included(configuration: str | None, expected: bool) -> None:
    assert is_included(configuration, "dmx_config_ui.yaml") is expected


def test_add_include_keeps_existing_light_key() -> None:
    original = "default_config:\nlight:\n  - platform: template\n"
    updated = add_include(original, "x.yaml")
    assert updated == original + "\nlight dmx_config_ui: !include x.yaml\n"
    assert add_include(updated, "x.yaml") == updated
    assert add_include(None, "x.yaml") == "light dmx_config_ui: !include x.yaml\n"


@pytest.mark.parametrize(
    ("value", "valid"),
    [
        ("dmx_config_ui.yaml", True),
        ("lights/artnet.yml", True),
        ("configuration.yaml", False),
        ("../secrets.yaml", False),
        ("/etc/passwd.yaml", False),
        ("lights.txt", False),
        ("", False),
        ("a\\b.yaml", False),
    ],
)
def test_is_valid_include_file(value: str, valid: bool) -> None:
    assert is_valid_include_file(value) is valid


def test_render_dmx() -> None:
    content = render_dmx_yaml({"fixtures_folder": "fixtures"})
    assert content.startswith("# Generated by DMX Config UI")
    assert yaml.safe_load(content) == {"fixtures": {"folder": "fixtures"}}


CONFIGURATION = (
    "default_config:\n"
    "dmx:\n"
    "  artnet:\n"
    "    universes:\n"
    "      - 1:\n"
    "\n"
    "          devices: []\n"
    "  # trailing comment of the block\n"
    "# comment before light\n"
    "light:\n"
    "  - platform: template\n"
)


@pytest.mark.parametrize(
    ("configuration", "key", "expected"),
    [
        (None, "dmx", None),
        ("", "dmx", None),
        (CONFIGURATION, "dmx", (1, 7)),
        (CONFIGURATION, "light", (9, 11)),
        (CONFIGURATION, "default_config", (0, 1)),
        ("dmxfoo:\n  a: 1\n", "dmx", None),
        ("dmx: !include x.yaml\n", "dmx", (0, 1)),
        ("  dmx:\n", "dmx", None),
    ],
)
def test_find_top_level_block(configuration, key: str, expected) -> None:
    assert find_top_level_block(configuration, key) == expected


def test_add_dmx_include_replaces_block() -> None:
    updated, replaced = add_dmx_include(CONFIGURATION, "gen.yaml")
    assert replaced is True
    assert updated == (
        "default_config:\n"
        "dmx: !include gen.yaml\n"
        "  # trailing comment of the block\n"
        "# comment before light\n"
        "light:\n"
        "  - platform: template\n"
    )
    assert yaml.safe_load(updated.replace("!include gen.yaml", "x"))["light"]
    assert add_dmx_include(updated, "gen.yaml") == (updated, False)


def test_add_dmx_include_appends() -> None:
    assert add_dmx_include(None, "gen.yaml") == ("dmx: !include gen.yaml\n", False)
    assert add_dmx_include("a: 1\n", "gen.yaml") == ("a: 1\n\ndmx: !include gen.yaml\n", False)
